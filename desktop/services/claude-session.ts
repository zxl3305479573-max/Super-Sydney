/**
 * Parser for Claude Code transcripts (~/.claude/projects/<project>/<session>.jsonl).
 *
 * Only two kinds of content are kept:
 *  - prompts the user actually typed (including slash commands such as /review)
 *  - the assistant's visible text
 * Tool inputs/outputs, thinking blocks, hook output, `!` shell commands,
 * injected reminders and subagent (sidechain) traffic are discarded. Tool
 * names and edited file paths are surfaced separately as metadata.
 */

export type ClaudeLine =
  | { kind: 'prompt'; uuid: string; sessionId: string; cwd: string; gitBranch: string; text: string; timestamp: string }
  | { kind: 'interrupt'; sessionId: string; timestamp: string }
  | { kind: 'assistant'; uuid: string; sessionId: string; cwd: string; messageId: string; text: string; tools: Array<{ name: string; files: string[]; reads: string[] }>; model: string; stopReason: string; timestamp: string }
  | { kind: 'turn_end'; sessionId: string; timestamp: string };

type Raw = Record<string, unknown>;

const FILE_TOOLS = new Set(['Edit', 'Write', 'MultiEdit', 'NotebookEdit']);

function str(value: unknown): string {
  return typeof value === 'string' ? value : '';
}

export function parseClaudeLine(line: string): ClaudeLine | null {
  let record: Raw;
  try {
    const value: unknown = JSON.parse(line);
    if (!value || typeof value !== 'object') return null;
    record = value as Raw;
  } catch {
    return null;
  }
  const sessionId = str(record.sessionId);
  const timestamp = str(record.timestamp);
  if (record.type === 'system' && (record.subtype === 'turn_duration' || record.subtype === 'stop_hook_summary')) {
    return { kind: 'turn_end', sessionId, timestamp };
  }
  if (record.type !== 'user' && record.type !== 'assistant') return null;
  if (record.isSidechain === true || record.isMeta === true || record.isCompactSummary === true || record.isVisibleInTranscriptOnly === true) return null;
  const message = record.message as Raw | undefined;
  if (!message || typeof message !== 'object') return null;
  const uuid = str(record.uuid);
  const cwd = str(record.cwd);

  if (record.type === 'user') {
    if (record.toolUseResult !== undefined) return null;
    const content = message.content;
    let raw = '';
    if (typeof content === 'string') raw = content;
    else if (Array.isArray(content)) {
      if (content.some(block => block && typeof block === 'object' && (block as Raw).type === 'tool_result')) return null;
      raw = content
        .filter(block => block && typeof block === 'object' && (block as Raw).type === 'text')
        .map(block => str((block as Raw).text))
        .join('\n');
    }
    if (/^\[Request interrupted by user/.test(raw.trim())) return { kind: 'interrupt', sessionId, timestamp };
    const text = cleanClaudePrompt(raw);
    if (!text || !uuid) return null;
    return { kind: 'prompt', uuid, sessionId, cwd, gitBranch: str(record.gitBranch), text, timestamp };
  }

  const blocks = Array.isArray(message.content) ? message.content as Raw[] : [];
  const texts: string[] = [];
  const tools: Array<{ name: string; files: string[]; reads: string[] }> = [];
  for (const block of blocks) {
    if (!block || typeof block !== 'object') continue;
    if (block.type === 'text' && str(block.text).trim()) texts.push(str(block.text));
    else if (block.type === 'tool_use') {
      const name = str(block.name);
      const input = (block.input && typeof block.input === 'object' ? block.input : {}) as Raw;
      const file = str(input.file_path) || str(input.notebook_path);
      if (name) tools.push({ name, files: FILE_TOOLS.has(name) && file ? [file] : [], reads: name === 'Read' && file ? [file] : [] });
    }
  }
  const text = texts.join('\n').trim();
  if (!text && !tools.length) return null;
  if (/^(?:API Error|No response requested\.)/.test(text) && !tools.length) return null;
  return {
    kind: 'assistant', uuid, sessionId, cwd,
    messageId: str(message.id) || uuid,
    text, tools,
    model: str(message.model),
    stopReason: str(message.stop_reason),
    timestamp
  };
}

/** Strip harness envelopes and keep only what the person typed. */
export function cleanClaudePrompt(value: string): string {
  let text = value.replace(/\r\n?/g, '\n').trim();
  if (!text) return '';
  // Output of local commands / `!` shell mode never counts as a prompt.
  if (/^<(?:local-command-stdout|local-command-stderr|bash-stdout|bash-stderr|bash-input)>/.test(text)) return '';
  if (/^Caveat: The messages below were generated by the user while running local commands/.test(text)) return '';
  if (/^This session is being continued from a previous conversation/.test(text)) return '';

  const command = text.match(/<command-name>\s*([^<]+?)\s*<\/command-name>/);
  if (command) {
    const args = text.match(/<command-args>([\s\S]*?)<\/command-args>/)?.[1]?.trim() ?? '';
    const name = command[1].startsWith('/') ? command[1] : `/${command[1]}`;
    // Built-in housekeeping commands carry no work content.
    if (/^\/(?:clear|compact|cost|exit|quit|help|status|model|config|login|logout|resume|context|usage|doctor|permissions|ide|memory|hooks|mcp|agents|vim|theme|terminal-setup)$/.test(name) && !args) return '';
    return args ? `${name} ${args}` : name;
  }

  text = text
    .replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '')
    .replace(/<user-prompt-submit-hook>[\s\S]*?<\/user-prompt-submit-hook>/g, '')
    .replace(/<ide_opened_file>[\s\S]*?<\/ide_opened_file>/g, '')
    .replace(/<ide_selection>[\s\S]*?<\/ide_selection>/g, '')
    .replace(/<command-message>[\s\S]*?<\/command-message>/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return text;
}
